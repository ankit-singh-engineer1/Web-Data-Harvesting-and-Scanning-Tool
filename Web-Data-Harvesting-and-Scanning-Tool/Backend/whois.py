import subprocess    # module to execute command-line tools

'''
Python script acts as the parent process, and when you use subprocess, 
it spawns a child process (a subordinate process) to run the external 
command-line tool (nmap, whois, etc.)

capture_output=True: Redirects both Standard Output (stdout) and Standard Error (stderr) away from printing directly to the terminal, storing them in memory inside the returned object.   
text=True: Tells Python to decode the stdout bytes directly into a standard Python string (str) rather than returning raw byte sequences (bytes).
timeout=60: Sets a strict execution limit of 60 seconds (1 minute). If whois takes longer than 1 minute to finish the scan, Python will interrupt the process and raise a TimeoutExpired exception.
.stdout: Accesses the captured standard text output generated by the Nmap scan and returns it.
'''

def get_whois(url):
    print("Getting whois...")
    try:
        return subprocess.run(["whois", url], 
                                capture_output=True, 
                                text=True, 
                                timeout=60).stdout
    except Exception as e:
        return f"whois not available or failed: {e}"













