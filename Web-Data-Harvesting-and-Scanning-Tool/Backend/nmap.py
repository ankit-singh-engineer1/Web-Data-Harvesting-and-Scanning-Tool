import subprocess    # start new applications/system commands, connect to their input/output pipes

'''

["nmap", *options.split(), ip]: The command list passed to the system.
"nmap": The binary command to execute.
*options.split(): Takes the options string (e.g., "-sV -sC"), splits it into individual list elements ["-sV", "-sC"], and uses the argument unpacking operator * to spread them into the command list.
ip: Appends the target IP address to the end of the command list.
Example constructed list: ["nmap", "-sV", "-F", "192.168.1.1"]
capture_output=True: Redirects both Standard Output (stdout) and Standard Error (stderr) away from printing directly to the terminal, storing them in memory inside the returned object.   
text=True: Tells Python to decode the stdout bytes directly into a standard Python string (str) rather than returning raw byte sequences (bytes).
timeout=120: Sets a strict execution limit of 120 seconds (2 minutes). If Nmap takes longer than 2 minutes to finish the scan, Python will interrupt the process and raise a TimeoutExpired exception.
.stdout: Accesses the captured standard text output generated by the Nmap scan and returns it.

'''

def get_nmap(options, ip):     # ()"-F" for options , domain name OR IP address for ip)
    print("Getting nmap ...")
    try:
        return subprocess.run(["nmap", *options.split(), ip], 
                                capture_output=True, 
                                text=True, 
                                timeout=120).stdout
    except Exception as e:
        return f"nmap not available or failed: {e}"











